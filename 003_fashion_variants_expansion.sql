BEGIN;

-- 1. Upgrade categories: Support hierarchy (parent_id) and gender target
ALTER TABLE public.categories
ADD COLUMN IF NOT EXISTS parent_id BIGINT REFERENCES public.categories(id) ON UPDATE CASCADE ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS gender VARCHAR(20) DEFAULT 'unisex' CHECK (gender IN ('men', 'women', 'unisex', 'kids')),
ADD COLUMN IF NOT EXISTS slug VARCHAR(120);

CREATE INDEX IF NOT EXISTS idx_categories_parent_id ON public.categories(parent_id);
CREATE INDEX IF NOT EXISTS idx_categories_gender ON public.categories(gender);

-- 2. Upgrade products: Add gender & brand if needed
ALTER TABLE public.products
ADD COLUMN IF NOT EXISTS gender VARCHAR(20) DEFAULT 'unisex' CHECK (gender IN ('men', 'women', 'unisex', 'kids')),
ADD COLUMN IF NOT EXISTS brand VARCHAR(100);

CREATE INDEX IF NOT EXISTS idx_products_gender ON public.products(gender);

-- 3. Product Images Gallery (Multiple angles/shots per item)
CREATE TABLE IF NOT EXISTS public.product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON UPDATE CASCADE ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    display_order INT NOT NULL DEFAULT 0,
    is_thumbnail BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_product_images_product_id ON public.product_images(product_id);

-- 4. Product Variants Table (Size, Color, SKU, Variant Stock & Price Override)
CREATE TABLE IF NOT EXISTS public.product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON UPDATE CASCADE ON DELETE CASCADE,
    size VARCHAR(50) NOT NULL, -- e.g. 'S', 'M', 'L', 'XL', '39', '40', '41', 'Free Size'
    color VARCHAR(50) NOT NULL, -- e.g. 'Đen', 'Trắng', 'Xanh Navy', 'Beige'
    color_code VARCHAR(20), -- e.g. '#000000', '#FFFFFF' for UI color swatch
    sku VARCHAR(100) UNIQUE,
    price_override NUMERIC(12, 2) CHECK (price_override IS NULL OR price_override >= 0),
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_product_size_color UNIQUE (product_id, size, color)
);

CREATE INDEX IF NOT EXISTS idx_variants_product_id ON public.product_variants(product_id);
CREATE INDEX IF NOT EXISTS idx_variants_size ON public.product_variants(size);
CREATE INDEX IF NOT EXISTS idx_variants_color ON public.product_variants(color);

-- 5. Link Cart Items with Product Variants
ALTER TABLE public.cart_items
ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES public.product_variants(id) ON UPDATE CASCADE ON DELETE CASCADE;

-- Update unique constraint to allow different variants of the same product in cart
ALTER TABLE public.cart_items
DROP CONSTRAINT IF EXISTS uq_cart_product;

-- New constraint: Unique per cart, product AND variant
CREATE UNIQUE INDEX IF NOT EXISTS uq_cart_product_variant
ON public.cart_items (cart_id, product_id, COALESCE(variant_id, 0));

-- 6. Link Order Items with Product Variants snapshot
ALTER TABLE public.order_items
ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES public.product_variants(id) ON UPDATE CASCADE ON DELETE SET NULL,
ADD COLUMN IF NOT EXISTS size_snapshot VARCHAR(50),
ADD COLUMN IF NOT EXISTS color_snapshot VARCHAR(50);

COMMIT;
